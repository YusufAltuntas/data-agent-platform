"""The initial migration builds the dap schema and matches the models."""

import uuid
from collections.abc import Iterator
from pathlib import Path

import pytest
import sqlalchemy as sa
from alembic import command
from alembic.config import Config

from dap.db.session import create_sync_engine
from dap.settings import Settings

pytestmark = pytest.mark.integration

ALEMBIC_INI = Path(__file__).resolve().parents[2] / "alembic.ini"

DAP_TABLES = {
    "teams",
    "memberships",
    "datasets",
    "dataset_grants",
    "runs",
    "run_events",
    "audit_log",
}


def _table_names(settings: Settings) -> set[str]:
    engine = create_sync_engine(settings)
    try:
        return set(sa.inspect(engine).get_table_names())
    finally:
        engine.dispose()


def _alembic_config(settings: Settings) -> Config:
    config = Config(ALEMBIC_INI)
    config.attributes["settings"] = settings
    return config


@pytest.fixture
def empty_db(settings: Settings) -> Iterator[Settings]:
    """Settings for a freshly created, empty database in the shared container."""
    name = f"dap_{uuid.uuid4().hex[:12]}"
    admin = create_sync_engine(settings, isolation_level="AUTOCOMMIT")
    try:
        with admin.connect() as conn:
            conn.execute(sa.text(f'CREATE DATABASE "{name}"'))
        yield settings.model_copy(update={"dap_db_name": name})
        with admin.connect() as conn:
            conn.execute(sa.text(f'DROP DATABASE "{name}" WITH (FORCE)'))
    finally:
        admin.dispose()


def test_upgrade_check_and_downgrade(empty_db: Settings) -> None:
    config = _alembic_config(empty_db)
    assert _table_names(empty_db) == set()

    command.upgrade(config, "head")
    assert _table_names(empty_db) == DAP_TABLES | {"alembic_version"}

    # Raises AutogenerateDiffsDetected if the models and the migration differ.
    command.check(config)

    command.downgrade(config, "base")
    assert _table_names(empty_db) == {"alembic_version"}


def test_migration_enforces_constraints(empty_db: Settings) -> None:
    command.upgrade(_alembic_config(empty_db), "head")
    engine = create_sync_engine(empty_db)
    try:
        with engine.begin() as conn:
            conn.execute(sa.text("INSERT INTO teams (id, name) VALUES ('sales', 'Sales')"))
            conn.execute(
                sa.text(
                    "INSERT INTO datasets (id, name, description, db_role)"
                    " VALUES ('sales', 'Sales', 'Orders', 'ds_sales_ro')"
                )
            )
            run_id = conn.execute(
                sa.text(
                    "INSERT INTO runs (id, team_id, dataset_id, created_by, question, status)"
                    " VALUES (gen_random_uuid(), 'sales', 'sales', 'alice@example.com', 'q',"
                    " 'queued') RETURNING id"
                )
            ).scalar_one()
            attempts = conn.execute(
                sa.text("SELECT attempts FROM runs WHERE id = :id"), {"id": run_id}
            ).scalar_one()
            assert attempts == 0

        rejected = [
            "INSERT INTO memberships (team_id, email, role) VALUES ('sales', 'a@x.com', 'owner')",
            "INSERT INTO runs (id, team_id, dataset_id, created_by, question, status)"
            " VALUES (gen_random_uuid(), 'sales', 'sales', 'a@x.com', 'q', 'done')",
            "INSERT INTO dataset_grants (team_id, dataset_id) VALUES ('nope', 'sales')",
        ]
        for statement in rejected:
            with pytest.raises(sa.exc.IntegrityError), engine.begin() as conn:
                conn.execute(sa.text(statement))

        event = (
            "INSERT INTO run_events (run_id, seq, attempt, type, payload)"
            " VALUES (:run_id, 1, 1, 'status', '{}')"
        )
        with engine.begin() as conn:
            conn.execute(sa.text(event), {"run_id": run_id})
        with pytest.raises(sa.exc.IntegrityError), engine.begin() as conn:
            conn.execute(sa.text(event), {"run_id": run_id})
    finally:
        engine.dispose()
